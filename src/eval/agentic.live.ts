/**
 * LIVE evaluation and end-to-end verification of the LLM integration.
 *
 *   npm run eval:live
 *
 * Reads the same configuration as the server (.env.local, then the process environment)
 * and runs the real five-agent investigation through the configured provider. It refuses
 * to run with no provider or with the scripted test double, so a result file from this
 * script always comes from a real model.
 *
 * Cases: the three physical fault scenarios and the flagship cyber-physical scenario
 * (cp-fan-setpoint). ATLAS_LIVE_SCENARIOS=cp-fan-setpoint,pump-bearing selects a subset;
 * on a CPU-only machine one investigation can take hours.
 *
 * Results: eval/results/agentic-live.{json,md}, rewritten after EVERY scenario with
 * `complete: false` until the last one finishes, so an interrupted run keeps what it
 * finished. The cost estimate uses list prices (zero for a local model).
 */
import { loadEnv } from 'vite';
import { describe, expect, it } from 'vitest';
import { runInvestigation } from '../agents/orchestrator';
import type { InvestigationReport } from '../agents/report';
import { configureAi } from '../../server/atlasAi';
import { scenarioCase, scoreReport } from './agentic';
import type { Score } from './agentic';
import { CYBER_PHYSICAL_FLAGSHIP, FAULTS } from './groundTruth';
import { num, pct, table, writeResults } from './results';

const ALL_CASES = [...FAULTS, CYBER_PHYSICAL_FLAGSHIP];

function selectedCases(env: Record<string, string>) {
  const wanted = (env.ATLAS_LIVE_SCENARIOS ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
  if (wanted.length === 0) return ALL_CASES;
  const unknown = wanted.filter((w) => !ALL_CASES.some((c) => c.scenario === w));
  if (unknown.length) throw new Error(`Unknown ATLAS_LIVE_SCENARIOS: ${unknown.join(', ')}. Known: ${ALL_CASES.map((c) => c.scenario).join(', ')}`);
  return ALL_CASES.filter((c) => wanted.includes(c.scenario));
}

function markdown(scores: Score[], meta: { provider: string; model: string; effort: string; complete: boolean; planned: number }): string {
  const totalCost = scores.reduce((a, s) => a + (s.estimatedCostUsd ?? 0), 0);
  return `
## Agent layer — LIVE model evaluation

Generated by \`npm run eval:live\` on ${new Date().toISOString()}. Provider ${meta.provider}, model ${meta.model}, effort ${meta.effort}. One run per scenario at the default seed, investigated 150 s after injection. Every number below comes from a real model response.${meta.complete ? '' : `\n\n**Incomplete:** ${scores.length} of ${meta.planned} scenarios finished when this file was written.`}

### Run outcome, latency and cost

${table(['Scenario', 'Status', 'Agents (status / calls)', 'Model calls', 'Repairs', 'Duration s', 'Input tokens', 'Output tokens', 'Est. cost USD'], scores.map((s) => [s.scenario, s.status, Object.entries(s.agents).map(([k, a]) => `${k.replace(/_analyst|investigation_/g, '')} ${a.status}/${a.attempts}`).join(', '), s.modelCalls, s.repairs, num(s.durationS), s.inputTokens, s.outputTokens, s.estimatedCostUsd === null ? 'n/a' : s.estimatedCostUsd.toFixed(3)]))}

Estimated total: ${totalCost.toFixed(3)} USD (token counts × list price; not a bill).

### Evidence grounding (all model answers, including ones later repaired)

${table(['Scenario', 'Citations accepted', 'Cyber events cited', 'Invented evidence IDs', 'Invented assets', 'Invented hypotheses', 'Uncited observations', 'Certainty / probability wording', 'Causal overreach', 'Schema failures', 'Claims checked', 'Unsupported-claim rate', 'Figures flagged'], scores.map((s) => [s.scenario, s.citationsAccepted, s.cyberCitationsAccepted, s.invalidCitationsInRawAnswers, s.unknownAssetsInRawAnswers, s.unknownHypothesesInRawAnswers, s.uncitedObservationsInRawAnswers, s.certaintyOrProbabilityWording, s.causalOverreachInRawAnswers, s.schemaFailures, s.claimsChecked, pct(s.unsupportedClaimRate), s.figuresFlagged]))}

Validation issues by code: ${scores.map((s) => `${s.scenario}: ${Object.entries(s.issueCodes).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'}`).join('; ')}.

### Reasoning against ground truth and against the deterministic engine

${table(['Scenario', 'Ground truth', 'Deterministic lead', 'AI lead', 'AI standing', 'AI stance on true hypothesis', 'Alternatives given a contradiction', 'Challenge to leading', 'At-risk assets covered', 'First check on true origin', 'Checks linked to hypotheses', 'Disagreements recorded'], scores.map((s) => [s.scenario, s.truthLead, s.deterministicLead ?? 'none', s.aiLead ?? 'none', s.standing ?? 'n/a', s.truthStance ?? 'n/a', `${s.alternativesWithContradictions ?? 'n/a'} / ${s.alternativesAssessed ?? 'n/a'}`, String(s.challengeToLeadingGiven), pct(s.impactRecallOfDeterministicAtRisk), String(s.firstCheckOnOrigin), `${s.checksLinkedToHypotheses} / ${s.checks}`, s.disagreementsFound]))}

### Governance invariants

${table(['Scenario', 'Confirmed by AI', 'Incident unchanged by the run'], scores.map((s) => [s.scenario, String(s.confirmedByAi), String(s.incidentUnchanged)]))}

Sample size is one run per scenario: these are observations, not statistics.
`;
}

describe('live model evaluation', () => {
  it('runs the five-agent investigation on the selected scenarios with a real model', async () => {
    const env = loadEnv('development', process.cwd(), '');
    const ai = configureAi(env);
    if (!ai.provider) throw new Error(`No live provider is configured, so nothing was measured. ${ai.reason ?? ''}`.trim());
    if (ai.provider.testDouble) throw new Error('The configured provider is the scripted test double. eval:live only measures a real model; unset ATLAS_LLM_PROVIDER=scripted.');
    const cases = selectedCases(env);

    const scores: Score[] = [];
    const reports: InvestigationReport[] = [];
    const save = (complete: boolean) => {
      const meta = { provider: ai.provider!.id, model: ai.provider!.model, effort: ai.effort, complete, planned: cases.length };
      writeResults('agentic-live', { generated: new Date().toISOString(), ...meta, scores, reports }, markdown(scores, meta));
    };

    for (const truth of cases) {
      const { incident, ctx, before } = scenarioCase(truth);
      process.stdout.write(`\n${truth.scenario}: investigating ${incident.id} with ${ai.provider.id} / ${ai.provider.model} ...\n`);
      const report = await runInvestigation(ctx, {
        provider: ai.provider,
        limits: ai.limits,
        price: ai.price,
        emit: (e) => {
          if (e.type === 'agent_finished') process.stdout.write(`  ${e.agent.padEnd(22)} ${e.status.padEnd(9)} ${(e.latencyMs / 1000).toFixed(1)} s, ${e.attempts} call(s)\n`);
          if (e.type === 'run_failed') process.stdout.write(`  run failed: ${e.message}\n`);
        },
      });
      reports.push(report);
      const s = scoreReport(report, incident, truth, before);
      scores.push(s);
      process.stdout.write(`  -> ${report.status}${report.failure ? ` (${report.failure})` : ''}, ${s.modelCalls} calls, ${s.durationS.toFixed(1)} s\n`);
      save(scores.length === cases.length);
    }

    console.log(markdown(scores, { provider: ai.provider.id, model: ai.provider.model, effort: ai.effort, complete: true, planned: cases.length }));
    for (const s of scores) {
      expect(s.confirmedByAi).toBe(false);
      expect(s.incidentUnchanged).toBe(true);
    }
    expect(scores.some((s) => s.status !== 'failed')).toBe(true);
  });
});
